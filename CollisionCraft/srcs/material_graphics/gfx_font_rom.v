// =============================================================================
//  gfx_font_rom.v  --  5x7 pixel font
// -----------------------------------------------------------------------------
//  OWNER: PERSON 1  (Materials, Graphics & Controls)
//
//  Give it an ASCII character and a row number (0 = top, 6 = bottom) and it
//  returns the 5 pixels of that row. Bit 4 is the LEFTMOST pixel.
//
//  Lower-case letters are drawn as upper-case. A few symbols are redefined
//  for the game's UI:  '~' = down arrow,  '^' = up arrow,  '*' = star,
//  '#' = solid block.
//
//  Each glyph has its picture drawn in the comment next to it, so you can
//  edit a letter just by changing the 1s and 0s.
// =============================================================================
`default_nettype none

module gfx_font_rom (
    input  wire [7:0] ch,     // ASCII code
    input  wire [2:0] row,    // 0..6
    output reg  [4:0] bits    // bit 4 = leftmost pixel
);

    // Fold lower case onto upper case
    wire [7:0] c = (ch >= "a" && ch <= "z") ? (ch - 8'd32) : ch;

    reg [34:0] glyph;   // 7 rows x 5 bits, row 0 in the top bits

    always @* begin
        case (c)
            "A"   : glyph = 35'b01110100011000111111100011000110001; // .###. #...# #...# ##### #...# #...# #...#   A
            "B"   : glyph = 35'b11110100011000111110100011000111110; // ####. #...# #...# ####. #...# #...# ####.   B
            "C"   : glyph = 35'b01110100011000010000100001000101110; // .###. #...# #.... #.... #.... #...# .###.   C
            "D"   : glyph = 35'b11110100011000110001100011000111110; // ####. #...# #...# #...# #...# #...# ####.   D
            "E"   : glyph = 35'b11111100001000011110100001000011111; // ##### #.... #.... ####. #.... #.... #####   E
            "F"   : glyph = 35'b11111100001000011110100001000010000; // ##### #.... #.... ####. #.... #.... #....   F
            "G"   : glyph = 35'b01110100011000010111100011000101111; // .###. #...# #.... #.### #...# #...# .####   G
            "H"   : glyph = 35'b10001100011000111111100011000110001; // #...# #...# #...# ##### #...# #...# #...#   H
            "I"   : glyph = 35'b01110001000010000100001000010001110; // .###. ..#.. ..#.. ..#.. ..#.. ..#.. .###.   I
            "J"   : glyph = 35'b00111000100001000010000101001001100; // ..### ...#. ...#. ...#. ...#. #..#. .##..   J
            "K"   : glyph = 35'b10001100101010011000101001001010001; // #...# #..#. #.#.. ##... #.#.. #..#. #...#   K
            "L"   : glyph = 35'b10000100001000010000100001000011111; // #.... #.... #.... #.... #.... #.... #####   L
            "M"   : glyph = 35'b10001110111010110101100011000110001; // #...# ##.## #.#.# #.#.# #...# #...# #...#   M
            "N"   : glyph = 35'b10001100011100110101100111000110001; // #...# #...# ##..# #.#.# #..## #...# #...#   N
            "O"   : glyph = 35'b01110100011000110001100011000101110; // .###. #...# #...# #...# #...# #...# .###.   O
            "P"   : glyph = 35'b11110100011000111110100001000010000; // ####. #...# #...# ####. #.... #.... #....   P
            "Q"   : glyph = 35'b01110100011000110001101011001001101; // .###. #...# #...# #...# #.#.# #..#. .##.#   Q
            "R"   : glyph = 35'b11110100011000111110101001001010001; // ####. #...# #...# ####. #.#.. #..#. #...#   R
            "S"   : glyph = 35'b01111100001000001110000010000111110; // .#### #.... #.... .###. ....# ....# ####.   S
            "T"   : glyph = 35'b11111001000010000100001000010000100; // ##### ..#.. ..#.. ..#.. ..#.. ..#.. ..#..   T
            "U"   : glyph = 35'b10001100011000110001100011000101110; // #...# #...# #...# #...# #...# #...# .###.   U
            "V"   : glyph = 35'b10001100011000110001100010101000100; // #...# #...# #...# #...# #...# .#.#. ..#..   V
            "W"   : glyph = 35'b10001100011000110101101011010101010; // #...# #...# #...# #.#.# #.#.# #.#.# .#.#.   W
            "X"   : glyph = 35'b10001100010101000100010101000110001; // #...# #...# .#.#. ..#.. .#.#. #...# #...#   X
            "Y"   : glyph = 35'b10001100011000101010001000010000100; // #...# #...# #...# .#.#. ..#.. ..#.. ..#..   Y
            "Z"   : glyph = 35'b11111000010001000100010001000011111; // ##### ....# ...#. ..#.. .#... #.... #####   Z
            "0"   : glyph = 35'b01110100011001110101110011000101110; // .###. #...# #..## #.#.# ##..# #...# .###.   0
            "1"   : glyph = 35'b00100011000010000100001000010001110; // ..#.. .##.. ..#.. ..#.. ..#.. ..#.. .###.   1
            "2"   : glyph = 35'b01110100010000100010001000100011111; // .###. #...# ....# ...#. ..#.. .#... #####   2
            "3"   : glyph = 35'b11111000100010000010000011000101110; // ##### ...#. ..#.. ...#. ....# #...# .###.   3
            "4"   : glyph = 35'b00010001100101010010111110001000010; // ...#. ..##. .#.#. #..#. ##### ...#. ...#.   4
            "5"   : glyph = 35'b11111100001111000001000011000101110; // ##### #.... ####. ....# ....# #...# .###.   5
            "6"   : glyph = 35'b00110010001000011110100011000101110; // ..##. .#... #.... ####. #...# #...# .###.   6
            "7"   : glyph = 35'b11111000010001000100010000100001000; // ##### ....# ...#. ..#.. .#... .#... .#...   7
            "8"   : glyph = 35'b01110100011000101110100011000101110; // .###. #...# #...# .###. #...# #...# .###.   8
            "9"   : glyph = 35'b01110100011000101111000010001001100; // .###. #...# #...# .#### ....# ...#. .##..   9
            "!"   : glyph = 35'b00100001000010000100001000000000100; // ..#.. ..#.. ..#.. ..#.. ..#.. ..... ..#..   !
            "."   : glyph = 35'b00000000000000000000000000110001100; // ..... ..... ..... ..... ..... .##.. .##..   .
            ","   : glyph = 35'b00000000000000000000011000010001000; // ..... ..... ..... ..... .##.. ..#.. .#...   ,
            ">"   : glyph = 35'b01000001000001000001000100010001000; // .#... ..#.. ...#. ....# ...#. ..#.. .#...   >
            "<"   : glyph = 35'b00010001000100010000010000010000010; // ...#. ..#.. .#... #.... .#... ..#.. ...#.   <
            "+"   : glyph = 35'b00000001000010011111001000010000000; // ..... ..#.. ..#.. ##### ..#.. ..#.. .....   +
            "-"   : glyph = 35'b00000000000000011111000000000000000; // ..... ..... ..... ##### ..... ..... .....   -
            "="   : glyph = 35'b00000000001111100000111110000000000; // ..... ..... ##### ..... ##### ..... .....   =
            ":"   : glyph = 35'b00000011000110000000011000110000000; // ..... .##.. .##.. ..... .##.. .##.. .....   :
            "?"   : glyph = 35'b01110100010000100010001000000000100; // .###. #...# ....# ...#. ..#.. ..... ..#..   ?
            "/"   : glyph = 35'b00000000010001000100010001000000000; // ..... ....# ...#. ..#.. .#... #.... .....   /
            "*"   : glyph = 35'b00100011101111101110110111000100000; // ..#.. .###. ##### .###. ##.## #...# .....   star
            8'h27 : glyph = 35'b00100001000100000000000000000000000; // ..#.. ..#.. .#... ..... ..... ..... .....   '
            "("   : glyph = 35'b00010001000100001000010000010000010; // ...#. ..#.. .#... .#... .#... ..#.. ...#.   (
            ")"   : glyph = 35'b01000001000001000010000100010001000; // .#... ..#.. ...#. ...#. ...#. ..#.. .#...   )
            "#"   : glyph = 35'b11111111111111111111111111111111111; // ##### ##### ##### ##### ##### ##### #####   solid block
            "~"   : glyph = 35'b00100001000010010101011100010000000; // ..#.. ..#.. ..#.. #.#.# .###. ..#.. .....   down arrow
            "^"   : glyph = 35'b00100011101010100100001000010000000; // ..#.. .###. #.#.# ..#.. ..#.. ..#.. .....   up arrow
            default: glyph = 35'b0;               // space and anything unknown
        endcase
        // pick the requested row (row 0 = bits 34..30)
        case (row)
            3'd0: bits = glyph[34:30];
            3'd1: bits = glyph[29:25];
            3'd2: bits = glyph[24:20];
            3'd3: bits = glyph[19:15];
            3'd4: bits = glyph[14:10];
            3'd5: bits = glyph[9:5];
            3'd6: bits = glyph[4:0];
            default: bits = 5'b0;
        endcase
    end

endmodule

`default_nettype wire
